// Writes the spring easings from shared/utils/spring.ts into app/assets/css/main.css as
// `linear()` tokens and `spring-*` utilities. Run after changing SPRINGS: npm run springs
import { readFile, writeFile } from 'node:fs/promises'
import { springCss } from '../shared/utils/spring.ts'

const FILE = 'app/assets/css/main.css'
const START = '/* springs:start — generated by `npm run springs`, do not edit by hand */'
const END = '/* springs:end */'

const css = await readFile(FILE, 'utf8')
const from = css.indexOf(START)
const to = css.indexOf(END)
if (from === -1 || to === -1) throw new Error(`${FILE} is missing the springs markers`)

await writeFile(FILE, css.slice(0, from) + START + '\n' + springCss() + END + css.slice(to + END.length))
console.log(`Updated springs in ${FILE}`)
